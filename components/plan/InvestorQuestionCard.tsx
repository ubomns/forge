import { motion } from 'framer-motion';
import type { InvestorQuestion, SectionId } from '@/lib/schema/business-plan';
import { SECTION_DISPLAY_NAMES, SECTION_ORDER } from '@/lib/schema/business-plan';
import { scrollToSection } from '@/components/plan/PlanTOC';

interface InvestorQuestionCardProps {
    question: InvestorQuestion;
    number: number;
}

function isValidSection(id: string): id is SectionId {
    return (SECTION_ORDER as readonly string[]).includes(id);
}

export function InvestorQuestionCard({ question, number }: InvestorQuestionCardProps) {
    const sectionId = question.section_id as string;
    const isJumpable = isValidSection(sectionId);
    const sectionLabel = isJumpable
        ? SECTION_DISPLAY_NAMES[sectionId as SectionId]
        : sectionId;

    return (
        <motion.div
            className="investor-question-card"
            initial={{ opacity: 0, y: 14 }}
            whileInView={{ opacity: 1, y: 0 }}
            viewport={{ once: true, margin: '-40px' }}
            transition={{ duration: 0.45, ease: [0.16, 1, 0.3, 1] }}
            data-testid="investor-question-card"
        >
            <div className="investor-question-number">{number}</div>
            <div className="investor-question-content">
                <div className="investor-question-text">{question.question}</div>
                <div className="investor-question-why">{question.why_it_matters}</div>
                {isJumpable && (
                    <button
                        type="button"
                        className="investor-question-jumplink"
                        onClick={() => scrollToSection(sectionId as SectionId)}
                    >
                        <svg width="10" height="10" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                            <line x1="5" y1="12" x2="19" y2="12" />
                            <polyline points="12 5 19 12 12 19" />
                        </svg>
                        {sectionLabel}
                    </button>
                )}
            </div>
        </motion.div>
    );
}

interface InvestorQuestionsListProps {
    questions: InvestorQuestion[];
}

export function InvestorQuestionsList({ questions }: InvestorQuestionsListProps) {
    if (!questions || questions.length === 0) return null;

    return (
        <motion.div
            className="investor-questions-section"
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.4, ease: [0.16, 1, 0.3, 1] }}
            data-testid="investor-questions"
        >
            <div className="investor-questions-eyebrow">SECOND OPINION</div>
            <h3 className="investor-questions-title">
                The hardest questions an investor would ask
            </h3>
            <p className="investor-questions-sub">
                Generated by a third LLM call against the completed plan. Each question links to the
                section it targets.
            </p>
            <div className="investor-questions-list">
                {questions.map((q, i) => (
                    <InvestorQuestionCard key={i} question={q} number={i + 1} />
                ))}
            </div>
        </motion.div>
    );
}
